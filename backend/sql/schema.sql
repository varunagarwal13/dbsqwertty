-- 1. Customer
CREATE TABLE Customer (
    Customer_ID VARCHAR2(20) PRIMARY KEY,
    First_Name VARCHAR2(50) NOT NULL,
    Last_Name VARCHAR2(50) NOT NULL,
    Email VARCHAR2(100) UNIQUE NOT NULL,
    Phone_No VARCHAR2(20),
    House_No VARCHAR2(50),
    Street VARCHAR2(100),
    City VARCHAR2(50),
    State VARCHAR2(50),
    Pincode VARCHAR2(20),
    Registration_Date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Category
CREATE TABLE Category (
    Category_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Category_name VARCHAR2(100) NOT NULL,
    Description VARCHAR2(255)
);

-- 3. Product
CREATE TABLE Product (
    Product_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Product_Name VARCHAR2(100) NOT NULL,
    Brand VARCHAR2(50) NOT NULL,
    Price NUMBER(10,2) NOT NULL CHECK (Price >= 0),
    Category_ID NUMBER NOT NULL REFERENCES Category(Category_ID),
    Description CLOB
);

-- 4. Inventory
CREATE TABLE Inventory (
    Inventory_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Product_ID NUMBER UNIQUE NOT NULL REFERENCES Product(Product_ID),
    Available_Quantity NUMBER NOT NULL CHECK (Available_Quantity >= 0),
    Last_Updated_Date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. Cart
CREATE TABLE Cart (
    Cart_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Customer_ID VARCHAR2(20) UNIQUE NOT NULL REFERENCES Customer(Customer_ID),
    Created_Date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Cart_Status VARCHAR2(20) NOT NULL CHECK (Cart_Status IN ('ACTIVE', 'CHECKED_OUT', 'ABANDONED'))
);

-- 6. Cart_Item
CREATE TABLE Cart_Item (
    Cart_Item_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Cart_ID NUMBER NOT NULL REFERENCES Cart(Cart_ID),
    Product_ID NUMBER NOT NULL REFERENCES Product(Product_ID),
    Quantity NUMBER NOT NULL CHECK (Quantity > 0),
    UNIQUE (Cart_ID, Product_ID)
);

-- 7. Order_Tab
CREATE TABLE Order_Tab (
    Order_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Customer_ID VARCHAR2(20) NOT NULL REFERENCES Customer(Customer_ID),
    Order_Date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Order_Status VARCHAR2(20) NOT NULL CHECK (Order_Status IN ('PENDING', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED'))
);

-- 8. Order_Item
CREATE TABLE Order_Item (
    Order_Item_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Order_ID NUMBER NOT NULL REFERENCES Order_Tab(Order_ID),
    Product_ID NUMBER NOT NULL REFERENCES Product(Product_ID),
    Quantity NUMBER NOT NULL CHECK (Quantity > 0),
    Unit_Price NUMBER(10,2) NOT NULL CHECK (Unit_Price >= 0)
);

-- 9. Payment
CREATE TABLE Payment (
    Payment_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Order_ID NUMBER NOT NULL REFERENCES Order_Tab(Order_ID),
    Payment_mode VARCHAR2(50) NOT NULL,
    Payment_Status VARCHAR2(20) NOT NULL CHECK (Payment_Status IN ('PENDING', 'COMPLETED', 'FAILED', 'REFUNDED')),
    Payment_Date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Amount NUMBER(10,2) NOT NULL CHECK (Amount >= 0)
);

-- 10. Review
CREATE TABLE Review (
    Review_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Customer_ID VARCHAR2(20) NOT NULL REFERENCES Customer(Customer_ID),
    Product_ID NUMBER NOT NULL REFERENCES Product(Product_ID),
    Rating NUMBER(1) NOT NULL CHECK (Rating BETWEEN 1 AND 5),
    Comment_Text CLOB,
    Review_Date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

